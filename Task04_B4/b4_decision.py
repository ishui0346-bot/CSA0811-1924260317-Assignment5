"""B4 - Sentiment/summariser agreement, database index effect, production decision.
Run:  python Task04_B4/b4_decision.py     (writes outputs/B4_report.md)
"""
import random
import sqlite3
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
from complaints import COMPLAINTS  # noqa: E402
from shared.sentiment import STOPWORDS, first_k, label, summarise, tokenize  # noqa: E402

OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)
R = ["# B4 Report (generated by b4_decision.py)\n"]

# ------------------------------------------------------------ B4.1 sentiment agreement
R.append(f"## B4.1 Sentiment scorer vs my own labels ({len(COMPLAINTS)} complaints)\n")
pred = [label(t) for t, _ in COMPLAINTS]
gold = [g for _, g in COMPLAINTS]
agree = sum(p == g for p, g in zip(pred, gold))
R.append(f"**Agreement: {agree}/{len(COMPLAINTS)} = {100 * agree / len(COMPLAINTS):.0f}%**\n")
R.append("Confusion (rows = my label, columns = scorer):\n")
cats = ["positive", "negative", "neutral"]
conf = Counter(zip(gold, pred))
R.append("| mine \\ scorer | positive | negative | neutral |\n|---|---|---|---|")
for g in cats:
    R.append(f"| {g} | " + " | ".join(str(conf[(g, p)]) for p in cats) + " |")
R.append("\nMislabelled complaints (first 8) and why:\n")
wrong = [(t, g, p) for (t, g), p in zip(COMPLAINTS, pred) if g != p]
for t, g, p in wrong[:8]:
    R.append(f"- mine={g}, scorer={p}: \"{t[:95]}{'...' if len(t) > 95 else ''}\"")
R.append("\nTypical causes: sarcasm, words missing from the lexicon (e.g. 'unbearable', 'nobody'), "
         "negation separated from its word, and mixed opinions where positive and negative words cancel.\n")

# ------------------------------------------------------------ B4.1b summariser vs first-k
R.append("## B4.1b Summariser (frequent-word sentences) vs first-k sentences (k = 1)\n")


def top_words(text, n=4):
    c = Counter(w for w in tokenize(text) if w not in STOPWORDS and len(w) > 2)
    return [w for w, _ in c.most_common(n)]


def coverage(text, summary):
    keys = top_words(text)
    sw = set(tokenize(" ".join(summary)))
    return sum(k in sw for k in keys) / len(keys) if keys else 1.0


multi = [t for t, _ in COMPLAINTS]
cov_freq = [coverage(t, summarise(t, 1)) for t in multi]
cov_first = [coverage(t, first_k(t, 1)) for t in multi]
R.append(f"Quality measure = share of the complaint's 4 most frequent content words that appear in the summary.\n")
R.append(f"- frequent-word summariser: mean coverage **{100 * sum(cov_freq) / len(cov_freq):.0f}%**")
R.append(f"- first-k baseline:         mean coverage **{100 * sum(cov_first) / len(cov_first):.0f}%**")
better = sum(a > b for a, b in zip(cov_freq, cov_first))
same = sum(a == b for a, b in zip(cov_freq, cov_first))
R.append(f"- frequent-word better on {better} complaints, equal on {same}, worse on {len(multi) - better - same}.")
differ = [t for t in multi if summarise(t, 1) != first_k(t, 1)]
R.append(f"- the two methods choose a DIFFERENT sentence for {len(differ)} of {len(multi)} complaints.")
ex = (differ or multi)[0]
R.append(f"\nExample complaint:\n> {ex}\n\n- frequent-word: {summarise(ex, 1)}\n- first-k: {first_k(ex, 1)}\n")
R.append("Note: complaints are short (2-3 sentences) and rarely repeat a word, so the frequency score mostly favours the "
         "longest sentence, which is often the first one. The frequent-word method pays off on longer, rambling "
         "complaints where the main issue is repeated; for short ones first-k is almost as good and cheaper.\n")

reps = 200
t = time.perf_counter()
for _ in range(reps):
    for x in multi:
        summarise(x, 1)
t_freq = (time.perf_counter() - t) / (reps * len(multi))
t = time.perf_counter()
for _ in range(reps):
    for x in multi:
        first_k(x, 1)
t_first = (time.perf_counter() - t) / (reps * len(multi))
t = time.perf_counter()
for _ in range(reps):
    for x in multi:
        label(x)
t_score = (time.perf_counter() - t) / (reps * len(multi))
R.append(f"Time per complaint: sentiment scorer {t_score * 1e6:.1f} µs, frequent-word summary {t_freq * 1e6:.1f} µs, "
         f"first-k {t_first * 1e6:.1f} µs.  (first-k needs only the first sentence boundary, ~O(1)-ish in practice; "
         f"frequent-word is O(words); space O(words) for the Counter vs O(1) extra.)\n")
n_month = 50_000
R.append(f"At 50,000 complaints a month the scorer needs about {n_month * t_score:.2f} s and the summariser "
         f"{n_month * t_freq:.2f} s per month: computing time is not a concern.\n")

# ------------------------------------------------------------ B4.2 index
R.append("## B4.2 Effect of an index on (station, day)\n")
rnd = random.Random(3)
N_ST, DAYS = 120, 365
with tempfile.TemporaryDirectory() as d:
    con = sqlite3.connect(Path(d) / "aq.db")
    con.execute("CREATE TABLE aq (station TEXT, day TEXT, pm25 REAL)")
    from datetime import date, timedelta
    days = [(date(2026, 1, 1) + timedelta(days=i)).isoformat() for i in range(DAYS)]
    t0 = time.perf_counter()
    con.executemany("INSERT INTO aq VALUES (?,?,?)",
                    ((f"ST{s:03d}", dd, round(rnd.uniform(10, 150), 1))
                     for s in range(N_ST) for dd in days for _ in range(24)))
    con.commit()
    t_load = time.perf_counter() - t0
    nrows = con.execute("SELECT COUNT(*) FROM aq").fetchone()[0]
    QUERY = "SELECT AVG(pm25) FROM aq WHERE station = ? AND day BETWEEN ? AND ?"
    PARAMS = [(f"ST{rnd.randrange(N_ST):03d}", "2026-10-01", "2026-10-31") for _ in range(30)]

    def run_queries():
        t = time.perf_counter()
        for p in PARAMS:
            con.execute(QUERY, p).fetchone()
        return (time.perf_counter() - t) / len(PARAMS)

    plan_before = con.execute("EXPLAIN QUERY PLAN " + QUERY, PARAMS[0]).fetchall()[0][-1]
    before = run_queries()
    t0 = time.perf_counter()
    con.execute("CREATE INDEX idx_station_day ON aq(station, day)")
    t_index = time.perf_counter() - t0
    plan_after = con.execute("EXPLAIN QUERY PLAN " + QUERY, PARAMS[0]).fetchall()[0][-1]
    after = run_queries()
    con.close()
R.append(f"Table size: {nrows:,} rows (120 stations x 365 days x 24 readings); loaded in {t_load:.2f} s "
         f"({nrows / t_load:,.0f} rows/s).\n")
R.append(f"Query: `{QUERY}` (average of one station for one month)\n")
R.append(f"- before index: **{before * 1000:.2f} ms** per query; plan: `{plan_before}`")
R.append(f"- after index:  **{after * 1000:.3f} ms** per query; plan: `{plan_after}`")
R.append(f"- speed-up: **{before / after:,.0f}x**; building the index took {t_index:.2f} s once "
         f"(and adds extra disk space and slightly slower inserts).\n")

# ------------------------------------------------------------ B4.3 decision
new_rows_year = (12 + 100) * 96 * 365
R.append("## B4.3 Production decision (justified with the measurements above)\n")
R.append(f"""Scale: (12 + 100) stations x 96 readings/day x 365 = **{new_rows_year:,} readings/year** (about {new_rows_year / nrows:.1f}x the
table tested above) and 50,000 complaints/month.

**Storage.** Keep a relational database. SQLite (with `?` placeholders, `executemany`, and the (station, day) index) handled
{nrows:,} rows with one-month queries in {after * 1000:.2f} ms. At ~{new_rows_year / 1e6:.1f} M rows/year a single file is still
possible for a single writer, but 112 stations writing every 15 minutes, plus dashboards reading at the same time, suggests a
server database (PostgreSQL, optionally partitioned by month) for concurrent writers and backups. The schema from A1 stays the same.

**Cleaning.** Clean each station file incrementally when it arrives (a daily or 15-minute batch) instead of re-reading history.
Use pandas/vectorised cleaning for batches (B1 measured about 5-6x faster than loops at 1,000,000 rows) and keep the same
rules, plus the input validation from B2 (header, delimiter, encoding, empty file). Keep raw files unchanged for audit.

**Analysis.** Daily and monthly summaries by SQL GROUP BY on indexed data (B3: all methods are O(n) but SQL avoids reloading
history); pandas only for ad-hoc analysis and charts.

**AI methods.** The word-list scorer and extractive summariser cost about {t_score * 1e6:.0f} µs and {t_freq * 1e6:.0f} µs per complaint,
so 50,000 complaints are processed in seconds. But the scorer agreed with my labels on {100 * agree / len(COMPLAINTS):.0f}% of {len(COMPLAINTS)}
complaints (an optimistic figure: the lexicon was extended while I was reading these same complaints, so on new data it will be lower), and B2 showed systematic failures (sarcasm, double negatives, mixed opinions). Decision: use the lexicon scorer only as
a cheap first filter (e.g. routing obviously negative complaints), and train/fine-tune a small supervised model (e.g. Naive Bayes
or logistic regression on TF-IDF, or a pre-trained language model) on human-labelled complaints for the reported sentiment. Compute
is not the obstacle; accuracy is. Re-measure agreement on a larger labelled sample before and after switching.
""")
(OUT / "B4_report.md").write_text("\n".join(R), encoding="utf-8")
print("\n".join(R))
