"""B3 - Loops vs pandas vs SQL: correctness, scaling, profiling, running-sum alternative.
Run:  python Task03_B3/b3_benchmark.py       (about 1-2 minutes; writes outputs/B3_results.md)
"""
import cProfile
import csv
import io
import pstats
import sqlite3
import statistics
import sys
import tempfile
import time
import tracemalloc
from collections import defaultdict
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from shared.aq_gen import write_big_file  # noqa: E402

OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)


# ----------------------------------------------------------- the three methods
def by_loops(path):
    """Plain Python: store all readings per (station, day), then statistics.mean."""
    groups = defaultdict(list)
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            groups[(row["station"], row["date"])].append(float(row["pm25"]))
    return {k: statistics.mean(v) for k, v in groups.items()}


def by_pandas(path):
    df = pd.read_csv(path)
    return df.groupby(["station", "date"])["pm25"].mean().to_dict()


def by_sql(path):
    con = sqlite3.connect(":memory:")
    con.execute("CREATE TABLE aq (station TEXT, day TEXT, pm25 REAL)")
    with open(path, newline="") as f:
        rd = csv.reader(f)
        next(rd)
        con.executemany("INSERT INTO aq VALUES (?,?,?)", ((a, b, float(c)) for a, b, c in rd))
    res = con.execute("SELECT station, day, AVG(pm25) FROM aq GROUP BY station, day").fetchall()
    con.close()
    return {(s, d): m for s, d, m in res}


def by_running_sum(path):
    """Alternative concept: one pass, running sum and count per (station, day)."""
    sums = defaultdict(lambda: [0.0, 0])
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            acc = sums[(row["station"], row["date"])]
            acc[0] += float(row["pm25"])
            acc[1] += 1
    return {k: s / n for k, (s, n) in sums.items()}


METHODS = {"loops (csv+statistics.mean)": by_loops, "pandas groupby": by_pandas,
           "SQL GROUP BY (load+query)": by_sql, "running sum (alternative)": by_running_sum}


def timed(fn, path):
    t = time.perf_counter()
    r = fn(path)
    return time.perf_counter() - t, r


def peak_mb(fn, path):
    tracemalloc.start()
    fn(path)
    p = tracemalloc.get_traced_memory()[1] / 1e6
    tracemalloc.stop()
    return p


def same(a, b, tol=1e-6):
    return a.keys() == b.keys() and all(abs(a[k] - b[k]) < tol for k in a)


md = ["# B3 Results (generated by b3_benchmark.py)\n"]
with tempfile.TemporaryDirectory() as tmp:
    tmp = Path(tmp)

    # ------------------------------------------------------- B3.1 correctness
    small = write_big_file(tmp / "small.csv", n_stations=3, days=10)
    results = {name: fn(small) for name, fn in METHODS.items()}
    ref = results["loops (csv+statistics.mean)"]
    md.append("## B3.1 Correctness on small data (3 stations x 10 days = 720 rows, 30 daily means)\n")
    for name, r in results.items():
        ok = same(ref, r)
        md.append(f"- {name}: {len(r)} groups, agrees with loops = **{ok}**")
        assert ok, name
    k0 = sorted(ref)[0]
    md.append(f"\nExample: {k0} -> loops={ref[k0]:.4f}, pandas={results['pandas groupby'][k0]:.4f}, "
              f"SQL={results['SQL GROUP BY (load+query)'][k0]:.4f}\n")
    print("\n".join(md))

    # ------------------------------------------------------- B3.2 scaling
    md.append("\n## B3.2 Timing at increasing sizes (seconds, one run each after generating the file)\n")
    md.append("| stations | rows | " + " | ".join(METHODS) + " |")
    md.append("|---|---|" + "---|" * len(METHODS))
    files = {}
    for n in (1, 12, 120):
        p = write_big_file(tmp / f"big_{n}.csv", n_stations=n, days=365)
        files[n] = p
        rows = n * 365 * 24
        cells, refres = [], None
        for name, fn in METHODS.items():
            dt, r = timed(fn, p)
            refres = refres or r
            assert same(refres, r), f"{name} disagrees at {n} stations"
            cells.append(f"{dt:.3f}")
        line = f"| {n} | {rows:,} | " + " | ".join(cells) + " |"
        md.append(line)
        print(line)

    # ------------------------------------------------------- memory (12 stations)
    md.append("\n### Peak memory at 12 stations (105,120 rows, tracemalloc, MB)\n")
    for name, fn in METHODS.items():
        m = peak_mb(fn, files[12])
        md.append(f"- {name}: {m:.1f} MB")
        print(name, f"{m:.1f} MB")

    # ------------------------------------------------------- B3.3 profile
    pr = cProfile.Profile()
    pr.enable()
    by_loops(files[12])
    pr.disable()
    s = io.StringIO()
    st = pstats.Stats(pr, stream=s).sort_stats("tottime")
    st.print_stats(8)
    prof = s.getvalue()
    (OUT / "profile_loops.txt").write_text(prof, encoding="utf-8")
    top = sorted(st.stats.items(), key=lambda kv: -kv[1][2])[0]
    top_name = f"{top[0][2]} ({Path(top[0][0]).name}:{top[0][1]})"
    md.append("\n## B3.3 cProfile of the plain-Python version (12 stations)\n")
    md.append("```\n" + "\n".join(prof.strip().splitlines()[:18]) + "\n```")
    md.append(f"\nFunction with the largest own time (tottime): **{top_name}**.\n")
    print("Profile top:", top_name)

md.append("""
## B3.4 Engineering trade-off

- All four methods give identical results (verified at every size), so the choice is about speed, memory and maintenance.
- All are O(n) in time. pandas has the smallest constant (C parser + vectorised groupby). In the plain-Python version the
  profile shows the largest own time is inside the csv reader (`__next__` of DictReader: parsing every row in Python-level
  code), followed by `statistics.mean`, which is slow because it converts to exact fractions; the running-sum version
  removes the second cost, which is why it is faster than the "store then mean" loops.
- tracemalloc only counts Python allocations, so SQLite's memory (its C heap) is under-reported; use the OS process
  monitor for a precise figure. The memory *shape* is what matters: loops O(n), running sum O(stations x days).
- SQL has to be *loaded* first (executemany); once loaded, repeated queries are fast and can use an index, so the
  database wins when many different questions are asked of the same data.
- **Quick one-time analysis -> pandas** (shortest code, fastest to write and run, easy to plot).
- **Daily automated report -> SQLite + SQL GROUP BY** (data persists, today's file is appended, queries are
  declarative, indexed, safe with `?`, and need not reload history each day).
- Running-sum alternative: still O(n) time but O(stations x days) memory instead of O(n), and avoids
  `statistics.mean`, so it is the best pure-Python choice for very large files.
""")
(OUT / "B3_results.md").write_text("\n".join(md), encoding="utf-8")
print("\nSaved", OUT / "B3_results.md")
